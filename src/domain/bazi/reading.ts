export function buildReading(chart: Chart) {
  const portrait = portraits[chart.dayMaster.stem];
  const partial = chart.input.unknownTime;
  const facts = chart.pillars.map((p) => `${p.label}: ${p.stem}${p.branch}`);
  const presentThemes = themes
    .map((theme) => ({
      ...theme,
      evidence: chart.pillars.flatMap((p) => [
        ...(p.key !== "day" && theme.gods.includes(p.tenGod)
          ? [`${p.label}: ${p.stem} — ${p.tenGod}`]
          : []),
        ...p.hiddenGods.flatMap((god, i) =>
          theme.gods.includes(god)
            ? [`${p.label}, скрытый ${p.hidden[i]} — ${god}`]
            : [],
        ),
      ]),
    }))
    .filter((theme) => theme.evidence.length);
  const max = Math.max(...Object.values(chart.distribution));
  const leading = elements.filter((el) => chart.distribution[el.id] === max);
  const absent = elements.filter((el) => chart.distribution[el.id] === 0);
  const combinations = chart.interactions.filter((r) =>
    r.kind.includes("combination"),
  );
  const clashes = chart.interactions.filter((r) => r.kind === "clash");
  const harms = chart.interactions.filter((r) => r.kind === "harm");
  const stars = [
    ...new Map(
      symbolicStars(chart)
        .filter((s) => s.kind === "star" && s.positions.length)
        .map((s) => [s.name, s]),
    ).values(),
  ];
  const boundaryNote = partial
    ? "Время рождения неизвестно: показана предварительная карта без часового столпа. В день солнечного перехода возможны разные годовой или месячный столпы; около границы суток может отличаться и дневной. Все пояснения ниже относятся к показанному варианту, рассчитанному на служебный полдень."
    : `Карта построена по введённому времени ${chart.input.time}. ${chart.input.timeMode === "mean-solar" ? `После поправки по долготе расчётное время: ${chart.method.localTime}; уравнение времени не применяется.` : "Используется гражданское время без солнечной поправки."}`;
  const sections: ReadingSection[] = [
    {
      id: "portrait",
      title: "С чего начинается ваш разбор",
      text: portrait.text,
      evidence: [
        `Ствол дня: ${chart.dayMaster.stem} · ${chart.dayMaster.polarity} ${elementOf(chart.dayMaster.element).name}`,
      ],
      question: portrait.question,
    },
    {
      id: "elements",
      title: "Что показывает состав карты",
      text: `В показанной карте ${leading.length > 1 ? "наибольшую одинаковую долю имеют" : "чаще представлен элемент"} ${leading.map((el) => el.name).join(", ")} — ${max}%${leading.length > 1 ? " каждый" : ""}. Это описание состава: сколько места занимают видимые и скрытые символы. Из него нельзя сделать вывод, что вы «сильный» или «слабый» человек, и нельзя автоматически назначить полезную стихию.${absent.length ? ` ${absent.map((el) => el.name).join(", ")} в этом подсчёте не представлены. Это не означает отсутствия соответствующих качеств в жизни или необходимости «добавить» элемент.` : " Все пять элементов представлены в этом подсчёте; это само по себе не означает идеальный баланс."}${partial ? " Часовой столп может изменить эти доли." : ""}`,
      evidence: elements.map(
        (el) => `${el.name}: ${chart.distribution[el.id]}%`,
      ),
      question:
        "Какие способы действия из разбора вы узнаёте по собственному опыту, а какие вам не подходят?",
    },
    ...presentThemes.map((theme, i) => ({
      id: `theme-${i}`,
      title: theme.title,
      text: theme.text,
      evidence: theme.evidence,
      question: theme.question,
    })),
    {
      id: "relations",
      title: "Как читать внутренние противоречия",
      text: `${combinations.length ? "Сочетания в карте — повод рассмотреть, как разные задачи и потребности могут работать вместе. Само сочетание ещё не доказывает превращение элементов. " : ""}${clashes.length ? "Есть столкновения: в традиционном разборе это язык различий и движения, а не обещание конфликта или плохого события. Полезно обсуждать, какие конкурирующие цели требуют отдельного времени или договорённости. " : "Поддерживаемые парные столкновения не обнаружены. Это не означает, что в жизни не бывает противоречий. "}${harms.length ? "Название «вред» также не следует понимать буквально; этот дополнительный маркер требует контекста всей карты." : ""}`,
      evidence: chart.interactions.map((r) => `${r.symbols}: ${r.name}`),
      question:
        "Какие две важные для вас задачи сейчас конкурируют за одни и те же время и внимание?",
    },
    {
      id: "stars",
      title: "Что добавляют символические звёзды",
      text: stars.length
        ? `В известных столпах найдены: ${stars.map((s) => s.name).join(", ")}. ${stars.map((s) => s.meaning).join(" ")} Эти образы помогают выбрать вопросы для разговора, но не устанавливают факты о вашей биографии. Например, звезда общения не гарантирует отношения, а звезда перемещений не обязывает переезжать.`
        : "Поддерживаемые символические звёзды в известных столпах не найдены. Из этого нельзя делать вывод об отсутствии способностей, помощи или возможностей. Звёзды — дополнительный слой, а не обязательный набор качеств.",
      evidence: stars.map(
        (s) => `${s.name}: ${s.basis}; ${s.positions.join(", ")}`,
      ),
      question:
        "Какие из этих тем сейчас имеют отношение к вашему реальному вопросу?",
    },
    {
      id: "periods",
      title: "Как понимать периоды жизни",
      text: partial
        ? "Без времени рождения точное начало десятилетних периодов не рассчитывается. Поэтому этот разбор не выбирает для вас текущий такт и не приписывает возрасту определённый сценарий. Годовые символы можно изучать отдельно, сохраняя неопределённость исходной карты."
        : `В расчёте показаны десятилетние периоды, их начало — ${chart.luckStart ?? "требует уточнения"}. Они описывают меняющийся символический контекст, а не расписание обязательных событий. Вкладки «Такты», «Годы жизни» и «Текущие энергии» позволяют сопоставить выбранный период с вашей картой; год смены такта нужно смотреть по точной дате.`,
      evidence: partial
        ? ["Часовой столп и точный Да Юнь не рассчитаны"]
        : [
            `Начало Да Юнь: ${chart.luckStart}`,
            `Направление: ${chart.forward ? "прямое" : "обратное"}`,
          ],
      question:
        "Какой конкретный период и какую жизненную задачу вы хотите обсудить с консультантом?",
    },
  ];
  const conclusion: Conclusion = {
    summary: `${partial ? "Предварительный разбор без известного часа рождения. " : ""}${portrait.text} В карте присутствуют темы: ${presentThemes.map((t) => t.title.toLowerCase()).join("; ")}. Какие из них действительно важны, следует сверить с вашим запросом и опытом.`,
    resources: presentThemes
      .map((t) => `${t.title}. ${t.text.split(". ")[0]}.`)
      .join("\n\n"),
    attention: `${sections.find((s) => s.id === "relations")!.text}\n\nСилу карты и полезные элементы нельзя определить только по процентам. Итоговая оценка требует совместного рассмотрения сезона, корней и взаимодействий.${partial ? " Час неизвестен, поэтому выводы по показанным трём столпам предварительны." : ""}`,
    recommendations: `1. ${portrait.action}\n2. Выберите одну тему из разбора, которая откликается, и запишите два конкретных примера из жизни.\n3. Сформулируйте один вопрос для консультации и небольшой шаг, результат которого можно проверить.`,
    questions: [
      portrait.question,
      ...presentThemes.slice(0, 2).map((t) => t.question),
      partial
        ? "Можно ли уточнить хотя бы диапазон времени рождения по документам или воспоминаниям семьи?"
        : "Насколько надёжно известно время рождения и нужно ли сравнить варианты около границы часа?",
      "Какую задачу вы хотите решить с помощью консультации?",
    ].join("\n"),
  };
  return {
    version: "reading-rules-1.0",
    partial,
    notice: readingNotice,
    boundaryNote,
    facts,
    sections,
    conclusion,
    action: portrait.action,
  };
}
